#!/usr/bin/env node

import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";

const PACKAGE_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SCHEMA_PATH = path.join(PACKAGE_ROOT, "src/v2/schemas/layer-manifest.schema.json");
const OUTPUT_PATH = path.join(PACKAGE_ROOT, "src/v2/layerManifestValidator.generated.ts");

async function generatedSource() {
  const schemaSource = await readFile(SCHEMA_PATH, "utf8");
  const schema = JSON.parse(schemaSource);
  const ajv = new Ajv2020({
    allErrors: true,
    strict: false,
    code: { source: true, esm: true, lines: true }
  });
  addFormats(ajv);
  const validator = ajv.compile(schema);
  let source = standaloneCode(ajv, validator)
    .replace(
      'const func2 = require("ajv/dist/runtime/ucs2length").default;',
      "const func2 = ucs2Length;"
    )
    .replace('const func0 = require("ajv/dist/runtime/equal").default;', "const func0 = deepEqual;")
    .replaceAll('require("ajv-formats/dist/formats").fullFormats', "fullFormats");

  if (/\brequire\s*\(|\bnew\s+Function\b|\beval\s*\(/.test(source)) {
    throw new Error("Generated manifest validator still contains dynamic code or CommonJS loads");
  }

  const digest = createHash("sha256").update(schemaSource).digest("hex");
  source = `/* eslint-disable */\n// @ts-nocheck -- deterministic AJV standalone output; regenerate instead of editing.\n// Generated by scripts/generate-layer-manifest-validator.mjs\n// Source schema SHA-256: ${digest}\nimport * as ucs2LengthRuntime from "ajv/dist/runtime/ucs2length.js";\nimport * as deepEqualRuntime from "ajv/dist/runtime/equal.js";\nimport { fullFormats } from "ajv-formats/dist/formats.js";\n\nconst ucs2Length = typeof ucs2LengthRuntime.default === "function"\n  ? ucs2LengthRuntime.default\n  : ucs2LengthRuntime.default.default;\nconst deepEqual = typeof deepEqualRuntime.default === "function"\n  ? deepEqualRuntime.default\n  : deepEqualRuntime.default.default;\n\n${source}`;
  return source.endsWith("\n") ? source : `${source}\n`;
}

const expected = await generatedSource();
if (process.argv.includes("--check")) {
  const current = await readFile(OUTPUT_PATH, "utf8").catch(() => "");
  if (current !== expected) {
    process.stderr.write(
      "Standalone layer-manifest validator is stale; run npm run generate:manifest-validator -w @mapos/layer-sdk\n"
    );
    process.exitCode = 1;
  } else {
    process.stdout.write("Standalone layer-manifest validator is synchronized\n");
  }
} else {
  await writeFile(OUTPUT_PATH, expected, "utf8");
  process.stdout.write(`Wrote ${path.relative(PACKAGE_ROOT, OUTPUT_PATH)}\n`);
}
